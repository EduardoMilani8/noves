/*
 * ERP sintetico do noves: estrutura.
 *
 * Imita o legado Delphi + Firebird tipico: banco WIN1252, dominios, generators,
 * collation PT_BR sem diferenciar acento, BLOB de texto, COMPUTED BY e GTT.
 *
 * Os scripts sao executados pelo isql da imagem oficial, com conexao NONE.
 * Por isso todos os arquivos ficam em ASCII puro: os acentos dos dados sao
 * montados com ASCII_CHAR() em 03-dados.sql, byte a byte em WIN1252.
 */

/* Dominios */
CREATE DOMAIN D_ID AS INTEGER NOT NULL;
CREATE DOMAIN D_FLAG AS CHAR(1) DEFAULT 'S' NOT NULL CHECK (VALUE IN ('S', 'N'));
CREATE DOMAIN D_VALOR AS NUMERIC(15,2) DEFAULT 0;
CREATE DOMAIN D_NOME AS VARCHAR(60) COLLATE WIN_PTBR;

/* Generators (estilo legado; identity so existe a partir do Firebird 3) */
CREATE GENERATOR GEN_CLIENTES_ID;
CREATE GENERATOR GEN_PRODUTOS_ID;
CREATE GENERATOR GEN_PEDIDOS_ID;
CREATE GENERATOR GEN_LOG_ID;

/* Excecao de negocio */
CREATE EXCEPTION E_ESTOQUE_INSUFICIENTE 'Estoque insuficiente para o produto';

CREATE TABLE CLIENTES (
    ID          D_ID,
    NOME        D_NOME NOT NULL,
    CPF_CNPJ    VARCHAR(18),
    ATIVO       D_FLAG,
    LIMITE      D_VALOR,
    DT_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UF          CHAR(2),
    OBS         VARCHAR(200),
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID)
);

CREATE TABLE PRODUTOS (
    ID        D_ID,
    CODIGO    CHAR(10) NOT NULL,
    DESCRICAO BLOB SUB_TYPE 1 SEGMENT SIZE 80,
    UNIDADE   CHAR(2) DEFAULT 'UN',
    PRECO     NUMERIC(15,4) NOT NULL,
    CUSTO     NUMERIC(15,4),
    ESTOQUE   NUMERIC(15,3) DEFAULT 0,
    MARGEM    COMPUTED BY (CASE WHEN CUSTO > 0 THEN (PRECO - CUSTO) * 100 / CUSTO END),
    ATIVO     D_FLAG,
    CONSTRAINT PK_PRODUTOS PRIMARY KEY (ID),
    CONSTRAINT UQ_PRODUTOS_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE PEDIDOS (
    ID         D_ID,
    CLIENTE_ID INTEGER NOT NULL,
    DT_PEDIDO  DATE NOT NULL,
    HR_PEDIDO  TIME,
    STATUS     CHAR(1) DEFAULT 'A' NOT NULL,
    TOTAL      D_VALOR,
    /* Coluna legada sem charset: a aplicacao gravava WIN1252 aqui. */
    OBS        VARCHAR(200) CHARACTER SET NONE,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT FK_PEDIDOS_CLIENTES FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (ID),
    CONSTRAINT CK_PEDIDOS_STATUS CHECK (STATUS IN ('A', 'F', 'C'))
);

CREATE TABLE ITENS (
    PEDIDO_ID  INTEGER NOT NULL,
    ITEM       SMALLINT NOT NULL,
    PRODUTO_ID INTEGER NOT NULL,
    QTDE       NUMERIC(15,3) NOT NULL,
    VL_UNIT    NUMERIC(15,4) NOT NULL,
    DESCONTO   DOUBLE PRECISION DEFAULT 0,
    CONSTRAINT PK_ITENS PRIMARY KEY (PEDIDO_ID, ITEM),
    CONSTRAINT FK_ITENS_PEDIDOS FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDOS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITENS_PRODUTOS FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS (ID)
);

CREATE INDEX IX_PEDIDOS_DATA ON PEDIDOS (DT_PEDIDO);
CREATE DESCENDING INDEX IX_PEDIDOS_TOTAL ON PEDIDOS (TOTAL);

/* Chave primaria de texto e coluna com nome entre aspas (caixa mista). */
CREATE TABLE CONFIGURACOES (
    CHAVE       VARCHAR(40) NOT NULL,
    VALOR       VARCHAR(200),
    "Descricao" VARCHAR(100),
    CONSTRAINT PK_CONFIGURACOES PRIMARY KEY (CHAVE)
);

/* Tabela sem chave primaria. */
CREATE TABLE MOVIMENTO_ESTOQUE (
    PRODUTO_ID INTEGER NOT NULL,
    DT_MOVTO   TIMESTAMP NOT NULL,
    TIPO       CHAR(1) NOT NULL,
    QTDE       NUMERIC(15,3) NOT NULL
);

CREATE TABLE LOG_AUDITORIA (
    ID       BIGINT NOT NULL,
    DT_HORA  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USUARIO  VARCHAR(63),
    TABELA   VARCHAR(63),
    OPERACAO CHAR(1),
    DETALHE  VARCHAR(500),
    CONSTRAINT PK_LOG_AUDITORIA PRIMARY KEY (ID)
);

CREATE GLOBAL TEMPORARY TABLE TMP_RELATORIO (
    CLIENTE_ID INTEGER,
    TOTAL      NUMERIC(15,2)
) ON COMMIT DELETE ROWS;

CREATE VIEW V_CLIENTES_ATIVOS (ID, NOME, UF, LIMITE) AS
    SELECT ID, NOME, UF, LIMITE FROM CLIENTES WHERE ATIVO = 'S';

COMMIT;
