/*
 * ERP sintetico do noves: procedures e triggers.
 *
 * Cada objeto planta pelo menos uma construcao que o noves assess precisa
 * encontrar (SUSPEND, UPDATE OR INSERT, IN AUTONOMOUS TRANSACTION, EXCEPTION,
 * WHEN SQLCODE, RDB$SET_CONTEXT, FIRST/SKIP, GTT, trigger multievento com
 * POSITION, trigger BI com GEN_ID).
 */

SET TERM ^ ;

/* Log em transacao autonoma: sobrevive ao ROLLBACK de quem chamou. */
CREATE PROCEDURE SP_LOG (TABELA VARCHAR(63), OPERACAO CHAR(1), DETALHE VARCHAR(500))
AS
BEGIN
    IN AUTONOMOUS TRANSACTION DO
        INSERT INTO LOG_AUDITORIA (ID, USUARIO, TABELA, OPERACAO, DETALHE)
        VALUES (GEN_ID(GEN_LOG_ID, 1),
                COALESCE(RDB$GET_CONTEXT('USER_SESSION', 'APP_USUARIO'), CURRENT_USER),
                :TABELA, :OPERACAO, :DETALHE);
END^

/* A aplicacao Delphi chama isto logo depois de conectar. */
CREATE PROCEDURE SP_DEFINE_USUARIO_APP (USUARIO VARCHAR(63))
AS
DECLARE VARIABLE R INTEGER;
BEGIN
    R = RDB$SET_CONTEXT('USER_SESSION', 'APP_USUARIO', :USUARIO);
END^

/* Selecionavel: devolve uma linha por SUSPEND. */
CREATE PROCEDURE SP_VENDAS_CLIENTE (CLIENTE_ID INTEGER)
RETURNS (PEDIDO_ID INTEGER, DT_PEDIDO DATE, TOTAL NUMERIC(15,2))
AS
BEGIN
    FOR SELECT P.ID, P.DT_PEDIDO, P.TOTAL
          FROM PEDIDOS P
         WHERE P.CLIENTE_ID = :CLIENTE_ID
         ORDER BY P.DT_PEDIDO
          INTO :PEDIDO_ID, :DT_PEDIDO, :TOTAL
    DO
        SUSPEND;
END^

/* Selecionavel que escreve numa GTT e pagina com FIRST/SKIP. */
CREATE PROCEDURE SP_TOP_CLIENTES (QTD INTEGER, PULAR INTEGER)
RETURNS (CLIENTE_ID INTEGER, NOME VARCHAR(60), TOTAL NUMERIC(15,2))
AS
BEGIN
    DELETE FROM TMP_RELATORIO;
    INSERT INTO TMP_RELATORIO (CLIENTE_ID, TOTAL)
        SELECT P.CLIENTE_ID, SUM(P.TOTAL)
          FROM PEDIDOS P
         WHERE P.STATUS <> 'C'
         GROUP BY P.CLIENTE_ID;

    FOR SELECT FIRST (:QTD) SKIP (:PULAR) T.CLIENTE_ID, C.NOME, T.TOTAL
          FROM TMP_RELATORIO T
          JOIN CLIENTES C ON C.ID = T.CLIENTE_ID
         ORDER BY T.TOTAL DESC, T.CLIENTE_ID
          INTO :CLIENTE_ID, :NOME, :TOTAL
    DO
        SUSPEND;
END^

/* Executavel com UPDATE OR INSERT ... MATCHING. */
CREATE PROCEDURE SP_UPSERT_PRODUTO (CODIGO CHAR(10), DESCRICAO VARCHAR(2000), PRECO NUMERIC(15,4))
RETURNS (ID INTEGER)
AS
BEGIN
    ID = (SELECT P.ID FROM PRODUTOS P WHERE P.CODIGO = :CODIGO);
    IF (ID IS NULL) THEN
        ID = GEN_ID(GEN_PRODUTOS_ID, 1);

    UPDATE OR INSERT INTO PRODUTOS (ID, CODIGO, DESCRICAO, PRECO)
        VALUES (:ID, :CODIGO, :DESCRICAO, :PRECO)
        MATCHING (CODIGO);
END^

/* Executavel com excecao nomeada e tratador WHEN SQLCODE. */
CREATE PROCEDURE SP_BAIXA_ESTOQUE (PRODUTO_ID INTEGER, QTDE NUMERIC(15,3))
AS
DECLARE VARIABLE SALDO NUMERIC(15,3);
BEGIN
    SELECT P.ESTOQUE FROM PRODUTOS P WHERE P.ID = :PRODUTO_ID INTO :SALDO;
    IF (SALDO IS NULL OR SALDO < QTDE) THEN
        EXCEPTION E_ESTOQUE_INSUFICIENTE;

    UPDATE PRODUTOS SET ESTOQUE = ESTOQUE - :QTDE WHERE ID = :PRODUTO_ID;
    EXECUTE PROCEDURE SP_LOG('PRODUTOS', 'U', 'Baixa de estoque do produto ' || :PRODUTO_ID);

    WHEN SQLCODE -901 DO
        EXCEPTION E_ESTOQUE_INSUFICIENTE 'Falha ao baixar o estoque';
END^

/* Triggers BI que so preenchem o ID com GEN_ID. */
CREATE TRIGGER CLIENTES_BI FOR CLIENTES
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN
        NEW.ID = GEN_ID(GEN_CLIENTES_ID, 1);
END^

CREATE TRIGGER PRODUTOS_BI FOR PRODUTOS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN
        NEW.ID = GEN_ID(GEN_PRODUTOS_ID, 1);
END^

CREATE TRIGGER PEDIDOS_BI FOR PEDIDOS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN
        NEW.ID = GEN_ID(GEN_PEDIDOS_ID, 1);
END^

/* Multievento com POSITION. Durante a carga inicial o contexto desliga a auditoria. */
CREATE TRIGGER PEDIDOS_AUDITORIA FOR PEDIDOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
DECLARE VARIABLE OPERACAO CHAR(1);
BEGIN
    IF (RDB$GET_CONTEXT('USER_SESSION', 'NOVES_CARGA') IS NOT NULL) THEN
        EXIT;

    IF (INSERTING) THEN
        OPERACAO = 'I';
    ELSE IF (UPDATING) THEN
        OPERACAO = 'U';
    ELSE
        OPERACAO = 'D';

    EXECUTE PROCEDURE SP_LOG('PEDIDOS', :OPERACAO,
        'Pedido ' || COALESCE(NEW.ID, OLD.ID));
END^

/* Mantem PEDIDOS.TOTAL. Roda antes da auditoria por causa do POSITION. */
CREATE TRIGGER ITENS_TOTAL FOR ITENS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 5
AS
BEGIN
    IF (UPDATING OR DELETING) THEN
        UPDATE PEDIDOS SET TOTAL = TOTAL - OLD.QTDE * OLD.VL_UNIT WHERE ID = OLD.PEDIDO_ID;
    IF (INSERTING OR UPDATING) THEN
        UPDATE PEDIDOS SET TOTAL = TOTAL + NEW.QTDE * NEW.VL_UNIT WHERE ID = NEW.PEDIDO_ID;
END^

SET TERM ; ^

COMMIT;
